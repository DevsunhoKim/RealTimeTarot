export function generateTarotReading(cards: TarotCardData[]): string {
    if (cards.length !== 3) {
        return "3장의 카드가 필요합니다.";
    }

    const [past, present, future] = cards;

    // 각 카드에 대한 상세 설명 생성 (800-1000자 분량)
    const pastDescription = DETAILED_CARD_DESCRIPTIONS[past.nameKr]?.[
        Math.floor(Math.random() * (DETAILED_CARD_DESCRIPTIONS[past.nameKr]?.length || 1))
    ] || `${past.description} 과거를 나타내는 카드야.`;

    const presentDescription = DETAILED_CARD_DESCRIPTIONS[present.nameKr]?.[
        Math.floor(Math.random() * (DETAILED_CARD_DESCRIPTIONS[present.nameKr]?.length || 1))
    ] || `${present.description} 현재를 나타내는 카드야.`;

    const futureDescription = DETAILED_CARD_DESCRIPTIONS[future.nameKr]?.[
        Math.floor(Math.random() * (DETAILED_CARD_DESCRIPTIONS[future.nameKr]?.length || 1))
    ] || `${future.description} 미래를 나타내는 카드야.`;

    // 현재와 미래에 대한 구체적 조언
    const presentAdvice = PRESENT_ADVICE[present.nameKr]?.[
        Math.floor(Math.random() * (PRESENT_ADVICE[present.nameKr]?.length || 1))
    ] || "지금은 네 직감을 믿고 나아가면 돼.";

    const futureAdvice = FUTURE_ADVICE[future.nameKr]?.[
        Math.floor(Math.random() * (FUTURE_ADVICE[future.nameKr]?.length || 1))
    ] || "앞으로는 밝은 미래가 기다리고 있어.";

    // 연결 문구
    const pastIntro = PAST_INTROS[Math.floor(Math.random() * PAST_INTROS.length)];
    const presentIntro = PRESENT_INTROS[Math.floor(Math.random() * PRESENT_INTROS.length)];
    const futureIntro = FUTURE_INTROS[Math.floor(Math.random() * FUTURE_INTROS.length)];
    const connection1 = CONNECTIONS[Math.floor(Math.random() * CONNECTIONS.length)];
    const connection2 = CONNECTIONS[Math.floor(Math.random() * CONNECTIONS.length)];
    const ending = ENDINGS[Math.floor(Math.random() * ENDINGS.length)];

    // 800-1000자 분량의 운세 텍스트 생성
    const reading = `${pastIntro} ${pastDescription}

${connection1} ${presentIntro} ${presentDescription} ${presentAdvice}

${connection2} ${futureIntro} ${futureDescription} ${futureAdvice}

${ending}`;

    return reading;
}
